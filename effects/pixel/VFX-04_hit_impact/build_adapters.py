#!/usr/bin/env python3
"""Generate only the Godot syntax adapter and preview preset copy; never bake frames."""
from pathlib import Path
import argparse, json, re
ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[2]
PREVIEW = REPO / 'preview/godot/effects/VFX-04_hit_impact'
KERNEL = ROOT / 'src/shared/ImpactKernel.hlsl'
HEADER = '''// GENERATED by effects/pixel/VFX-04_hit_impact/build_adapters.py; do not edit.
shader_type canvas_item;
render_mode unshaded, blend_mix;
uniform float age = -1.0;
uniform float duration = 0.20;
uniform float size = 1.0;
uniform float core_size = 6.0;
uniform float shard_count = 5.0;
uniform float shard_length = 8.0;
uniform float spread = 2.1816616;
uniform float speed = 78.0;
uniform float seed = 23.0;
uniform float shock = 0.0;
uniform float direction = 0.4363323;
uniform float extent = 64.0;
uniform vec4 core_color : source_color = vec4(1.0,0.960784,0.811765,1.0);
uniform vec4 body_color : source_color = vec4(0.933333,0.768627,0.392157,1.0);
uniform vec4 edge_color : source_color = vec4(0.650980,0.415686,0.219608,1.0);
'''
FOOTER = '''
void fragment() {
    // Quantize before rotation: every direction keeps the same world-oriented pixel grid.
    vec2 p = floor(UV * (extent * 2.0)) + vec2(0.5) - vec2(extent);
    p.y = -p.y;
    p = impactRotate(p, direction);
    float band = impactSample(p, age, duration, size, core_size, shard_count,
        shard_length, spread, speed, seed, shock);
    vec3 rgb = band > 2.5 ? core_color.rgb : (band > 1.5 ? body_color.rgb : edge_color.rgb);
    COLOR = vec4(rgb, band > 0.5 ? 1.0 : 0.0);
}
'''
def generated():
    kernel = KERNEL.read_text().replace('float2', 'vec2')
    header, footer = HEADER, FOOTER
    for name in re.findall(r'uniform \w+ (\w+)', HEADER):
        header = re.sub(r'\b'+name+r'\b', 'u_'+name, header)
        footer = re.sub(r'\b'+name+r'\b', 'u_'+name, footer)
    return {PREVIEW / 'impact.gdshader': header + kernel + footer,
            PREVIEW / 'presets.json': (ROOT / 'config/presets.json').read_text()}
def main():
    p = argparse.ArgumentParser(); p.add_argument('--check', action='store_true'); args=p.parse_args()
    for path, content in generated().items():
        if args.check:
            assert path.exists() and path.read_text() == content, f'Stale generated adapter: {path}'
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_text(content)
    json.loads((ROOT/'config/presets.json').read_text())
    print('PASS: shared kernel adapter and presets are in sync')
if __name__ == '__main__': main()
