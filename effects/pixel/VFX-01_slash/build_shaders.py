#!/usr/bin/env python3
"""Generate only the Godot syntax adapter; the canonical kernel stays engine-independent."""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[2]
KERNEL = ROOT / 'src/shared/SlashKernel.inc'
OUTPUT = REPO / 'preview/godot/slash.gdshader'


def generated_shader():
    kernel = KERNEL.read_text()
    kernel = re.sub(r'\bfloat2\b', 'vec2', kernel)
    kernel = re.sub(r'\batan2\b', 'atan', kernel)
    return '''// GENERATED by effects/pixel/VFX-01_slash/build_shaders.py. Do not edit.
shader_type canvas_item;
render_mode unshaded;
uniform float age = 0.0;
uniform float reach_px = 46.0;
uniform float thickness_px = 13.0;
uniform float sweep_radians = 1.954768762;
uniform float curvature = 0.82;
uniform float direction_radians = 0.0;
uniform float reverse_sign = 1.0;
uniform float start_seconds = 0.025;
uniform float burst_seconds = 0.065;
uniform float decay_seconds = 0.09;
uniform vec4 edge_color : source_color = vec4(1.0, 0.956862745, 0.807843137, 1.0);
uniform vec4 body_color : source_color = vec4(0.960784314, 0.772549020, 0.419607843, 1.0);
uniform vec4 tail_color : source_color = vec4(0.729411765, 0.462745098, 0.215686275, 1.0);
uniform vec2 center_px = vec2(100.0, 180.0);
uniform float display_scale = 1.0;

''' + kernel + '''
void fragment() {
    // Each enlarged pixel is the same sample as the 1x view (not re-rasterized).
    vec2 p = floor((FRAGCOORD.xy - center_px) / display_scale) + vec2(0.5);
    p.y = -p.y; // Canonical coordinates are +Y up.
    float band = slash_band(p, age, reach_px, thickness_px, sweep_radians,
        curvature, direction_radians, reverse_sign, start_seconds, burst_seconds, decay_seconds);
    vec3 rgb = band > 2.5 ? edge_color.rgb : (band > 1.5 ? body_color.rgb : tail_color.rgb);
    COLOR = vec4(rgb, band > 0.5 ? 1.0 : 0.0);
}
'''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generated_shader()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Godot adapter is stale: run build_shaders.py')
        print('Godot adapter matches canonical kernel.')
    else:
        OUTPUT.write_text(content)
        print(OUTPUT.relative_to(REPO))

if __name__ == '__main__':
    main()
