#!/usr/bin/env python3
"""Mechanical syntax adapter of pure shared math; no claim that engine scripts port."""
from pathlib import Path
import argparse
import re
ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[2]
OUT = REPO / 'preview/godot/effects/VFX-02_weapon_trail/trail.gdshader'
def generated_shader():
    kernel = (ROOT / 'src/shared/TrailKernel.inc').read_text()
    kernel = re.sub(r'\bfloat([234])\b', r'vec\1', kernel)
    return '''// GENERATED by effects/pixel/VFX-02_weapon_trail/build_shaders.py
shader_type canvas_item;
render_mode unshaded;
uniform vec4 trail_points[64];
uniform float trail_life[64];
uniform int trail_count = 0;
uniform float width_fraction = 0.68;
uniform float taper_power = 1.35;
uniform float opacity = 1.0;
uniform bool stepped_fade = false;
uniform float display_scale = 1.0;
uniform vec2 camera_pixels = vec2(0.0);
uniform vec4 core_color : source_color = vec4(1.0,0.9568627,0.8078431,1.0);
uniform vec4 body_color : source_color = vec4(0.9294118,0.7333333,0.3803922,1.0);
uniform vec4 edge_color : source_color = vec4(0.6745098,0.4352941,0.2078431,1.0);
varying vec2 world_pixels;
void vertex() {
    world_pixels = vec2(VERTEX.x, -VERTEX.y) / display_scale + camera_pixels;
}
''' + kernel + '''
void fragment() {
    vec2 p = floor(world_pixels) + vec2(0.5);
    vec2 best = vec2(-1.0);
    for (int i = 1; i < 64; i++) {
        if (i >= trail_count) { break; }
        vec2 hit = trail_segment(p, trail_points[i-1], trail_points[i],
            trail_life[i-1], trail_life[i], width_fraction, taper_power);
        if (hit.x > best.x) { best = hit; }
    }
    float band = trail_band(best);
    vec4 col = band > 2.5 ? core_color : (band > 1.5 ? body_color : edge_color);
    float fade = stepped_fade ? ceil(clamp(best.x, 0.0, 1.0) * 4.0) / 4.0 : 1.0;
    COLOR = vec4(col.rgb, band > 0.5 ? col.a * opacity * fade : 0.0);
}
'''
if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true')
    args = parser.parse_args(); content = generated_shader()
    if args.check:
        assert OUT.read_text() == content, 'Run build_shaders.py: adapter is stale'
        assert (OUT.parent / 'presets.json').read_text() == (ROOT / 'config/presets.json').read_text(), 'Preset copy is stale'
        print('PASS canonical math / Godot adapter parity')
    else:
        OUT.write_text(content)
        (OUT.parent / 'presets.json').write_text((ROOT / 'config/presets.json').read_text())
